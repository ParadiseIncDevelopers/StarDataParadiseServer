"""Verify transactional table design, authorization and History over local TLS."""

import argparse
from pathlib import Path
import secrets
import ssl
import tempfile

from history_restore_rpc import head, read_at
from service_smoke import certificates, connection, exchange, execute, listening, require, save_config
from sql_rpc import INVALID_ARGUMENT, NULL, client, i64, text, token, write


PERMISSION_DENIED = 1006


def select(session, sql):
    return session.query(sql)[0]


def rejected(session, sql, code=INVALID_ARGUMENT, *, in_transaction=False):
    reply = session.raw("query.prepare", sql=sql)
    if reply["ok"]:
        statement = reply["body"]["statement_id"]
        try:
            fields = {} if in_transaction else {"request_token": token()}
            reply = session.raw("execute", statement_id=statement, parameters={}, **fields)
        finally:
            session.call("statement_close", statement_id=statement)
    require(not reply["ok"] and reply["error"]["code"] == code, f"{sql} expected {code}: {reply}")


def catalog(objects, name):
    return next(item for item in objects if item["qualified_name"][-1] == name)


def editor_details(session, ddl_revision):
    objects = session.call("metadata")["objects"]
    table = catalog(objects, "items")
    parent = catalog(objects, "parent")
    require(table["schema_details"] is True and table["data_revision"] == ddl_revision and
            table["permissions"] == {verb: True for verb in ("select", "insert", "update", "delete", "ddl")}
            and table["row_locator"] == {"columns": [0], "kind": "primary_key"},
            "designer permissions, revision or primary locator are missing")
    columns = {column["name"]: column for column in table["columns"]}
    require(columns["amount"]["precision"] == 10 and columns["amount"]["scale"] == 3 and
            columns["serial"]["identity"] is True and columns["serial"]["has_default"] is False and
            columns["code"]["nullable"] is False and columns["code"]["default_sql"] == "'auto'",
            "designer lost decimal width, identity, default or nullability")
    check = next(rule for rule in table["constraints"] if rule["kind"] == "check")
    foreign = next(rule for rule in table["constraints"] if rule["kind"] == "foreign_key")
    index = catalog(objects, "ix_items")
    require('"label"' in check["check_sql"] and
            foreign["reference_table_id"] == parent["id"] and foreign["reference_columns"] == [0] and
            index["index"] == {"columns": [0], "unique": False, "table_id": table["id"]},
            "designer lost renamed CHECK reference, foreign key, or owning table of the index")


def exercise_ddl(session):
    write(session, "CREATE TABLE parent (id BIGINT PRIMARY KEY)", 0)
    write(session, "INSERT INTO parent VALUES (42)", 1)
    write(session, "CREATE TABLE items (id BIGINT PRIMARY KEY, amount DECIMAL(8,2),"
          " note TEXT CHECK (note <> ''))", 0)
    write(session, "CREATE INDEX ix_items ON items(id)", 0)
    before = write(session, "INSERT INTO items VALUES (1,11.23,'ok'),(2,25.00,NULL)", 2)["lsn"]
    saved = read_at(session, "items", before)["rows"]
    rejected(session, "ALTER TABLE items ALTER COLUMN amount TYPE DECIMAL(8,1)")
    rejected(session, "ALTER TABLE items ALTER COLUMN id TYPE DECIMAL(20,0)")
    require(head(session) == before, "rejected conversion or indexed edit published a revision")

    session.call("tx_begin")
    for sql in ("ALTER TABLE items RENAME COLUMN note TO label",
                "ALTER TABLE items ADD COLUMN code TEXT NOT NULL DEFAULT 'auto'",
                "ALTER TABLE items ADD COLUMN parent_id BIGINT NOT NULL DEFAULT 42",
                "ALTER TABLE items ADD CONSTRAINT fk_items FOREIGN KEY (parent_id) REFERENCES parent(id)",
                "ALTER TABLE items ADD COLUMN serial BIGINT GENERATED BY DEFAULT AS IDENTITY UNIQUE",
                "ALTER TABLE items ALTER COLUMN amount TYPE DECIMAL(10,3)",
                "ALTER TABLE items ADD COLUMN tail TEXT"):
        session.mutate(sql)
    rejected(session, "ALTER TABLE items ALTER COLUMN label SET NOT NULL", in_transaction=True)
    ddl = session.call("tx_commit", request_token=token())["lsn"]
    require(select(session, "SELECT serial,code,parent_id,tail FROM items ORDER BY id") ==
            [[i64(1), text("auto"), i64(42), NULL], [i64(2), text("auto"), i64(42), NULL]],
            "typed defaults, existing rows, identity or a legacy lazy NULL changed")
    require(read_at(session, "items", before)["rows"] == saved, "ALTER changed a prior History snapshot")
    new = read_at(session, "items", ddl)["rows"]
    require([row["row_id"] for row in new] == [row["row_id"] for row in saved],
            "ALTER rewrite changed stable row identities")
    entries = session.call("history_log", target="items", limit=256, **{"from": ddl, "to": ddl})["entries"]
    rewrites = [entry for entry in entries if entry["kind"] == "row"]
    require(len(rewrites) == 12 and "note" in rewrites[0]["before"]["values"] and
            "label" in rewrites[0]["after"]["values"], "History could not match both images to their schemas")
    editor_details(session, ddl)

    rejected(session, "ALTER TABLE parent DROP CONSTRAINT AT 0")
    rejected(session, "ALTER TABLE items DROP COLUMN label")
    rejected(session, "INSERT INTO items (id,label) VALUES (3,'')")
    rejected(session, "INSERT INTO items (id,parent_id) VALUES (3,43)")
    rejected(session, "ALTER TABLE items ADD CONSTRAINT unique_code UNIQUE (code)")
    require(head(session) == ddl, "failed dependency, check or uniqueness edits published a revision")

    session.call("tx_begin")
    session.mutate("ALTER TABLE items DROP CONSTRAINT AT 1")
    session.mutate("ALTER TABLE items DROP COLUMN label")
    session.mutate("ALTER TABLE items ALTER COLUMN code SET DEFAULT 'edited'")
    session.call("tx_rollback")
    require(head(session) == ddl and select(session, "SELECT label FROM items WHERE id=1") == [[text("ok")]],
            "rollback left a column change or revision")
    editor_details(session, ddl)

    write(session, "INSERT INTO items (id) VALUES (3)", 1)
    require(select(session, "SELECT serial,code FROM items WHERE id=3") == [[i64(3), text("auto")]],
            "identity or default changed after a rolled back statement")
    write(session, "ALTER TABLE items DROP CONSTRAINT AT 1", 0)
    write(session, "ALTER TABLE items DROP COLUMN label", 0)
    write(session, "ALTER TABLE items ALTER COLUMN code SET DEFAULT 'edited'", 0)
    write(session, "ALTER TABLE items ALTER COLUMN serial DROP IDENTITY", 0)
    write(session, "ALTER TABLE items ALTER COLUMN serial ADD GENERATED BY DEFAULT AS IDENTITY", 0)
    write(session, "INSERT INTO items (id) VALUES (4)", 1)
    require(select(session, "SELECT serial,code FROM items WHERE id=4") == [[i64(4), text("edited")]],
            "replacement identity did not start past retained values")
    write(session, "ALTER TABLE items ALTER COLUMN code DROP DEFAULT", 0)
    write(session, "ALTER TABLE items ALTER COLUMN code DROP NOT NULL", 0)
    write(session, "ALTER TABLE items DROP CONSTRAINT fk_items", 0)
    write(session, "ALTER TABLE parent DROP CONSTRAINT AT 0", 0)
    write(session, "INSERT INTO items (id,parent_id) VALUES (5,43)", 1)
    require(select(session, "SELECT serial,code,parent_id FROM items WHERE id=5") == [[i64(5), NULL, i64(43)]],
            "dropping default, NOT NULL and foreign key did not affect subsequent inserts")


def exercise_sequence_defaults(session):
    write(session, "CREATE SEQUENCE ticket_numbers", 0)
    write(session, "CREATE TABLE ticket_holders (id BIGINT PRIMARY KEY)", 0)
    before = write(session, "INSERT INTO ticket_holders VALUES (8),(9)", 2)["lsn"]
    rejected(session, "ALTER TABLE ticket_holders ADD COLUMN ticket BIGINT "
             "DEFAULT NEXT VALUE FOR ticket_numbers CHECK (ticket > 10)")
    require(head(session) == before, "failed sequence backfill published a revision")
    write(session, "ALTER TABLE ticket_holders ADD COLUMN ticket BIGINT "
          "NOT NULL DEFAULT NEXT VALUE FOR ticket_numbers", 0)
    require(select(session, "SELECT ticket FROM ticket_holders ORDER BY id") == [[i64(1)], [i64(2)]],
            "failed constraint backfill consumed sequence values")
    objects = session.call("metadata")["objects"]
    definition = catalog(objects, "ticket_holders")["columns"][1]
    require(definition["has_default"] and definition["default_sequence_id"] == catalog(objects, "ticket_numbers")["id"],
            "designer lost the sequence dependency of the default")


def exercise_acl(admin, port, context):
    write(admin, "CREATE TABLE no_locator (nullable_key BIGINT UNIQUE)", 0)
    write(admin, "CREATE TABLE alternative_locator (key_a BIGINT NOT NULL, key_b TEXT NOT NULL,"
          " UNIQUE (key_a,key_b))", 0)
    tables = admin.call("metadata")["objects"]
    require("row_locator" not in catalog(tables, "no_locator") and
            catalog(tables, "alternative_locator")["row_locator"] == {"columns": [0, 1], "kind": "unique"},
            "nullable unique keys qualified or safe composite keys were omitted")
    password = secrets.token_urlsafe(32)
    write(admin, "CREATE USER table_reader", 0)
    admin.call("password_set", username="table_reader", new_password=password, request_token=token())
    write(admin, "GRANT SELECT ON TABLE items TO USER table_reader", 0)
    original = head(admin)
    with connection(port, context) as stream:
        require(exchange(stream, 1, "hello")["ok"], "reader hello failed")
        require(exchange(stream, 2, "auth", {"username": "table_reader", "password": password})["ok"],
                "reader authentication failed")
        reply = exchange(stream, 3, "metadata")
        require(reply["ok"], "reader did not receive a catalog for its selected table")
        table = catalog(reply["body"]["objects"], "items")
        require(table["permissions"]["select"] and not table["permissions"]["ddl"] and
                "schema_details" not in table and "constraints" not in table and "row_locator" not in table and
                "data_revision" not in table and all("has_default" not in column for column in table["columns"]),
                "SELECT-only session received table editor details or a writable locator")
        denied = exchange(stream, 4, "query.prepare", {"sql": "ALTER TABLE items DROP COLUMN code"})
        if denied["ok"]:
            denied = exchange(stream, 5, "execute", {"statement_id": denied["body"]["statement_id"],
                                                     "request_token": token()})
        require(not denied["ok"] and denied["error"]["code"] == PERMISSION_DENIED,
                "SELECT-only session could alter a table")
    require(head(admin) == original, "unauthorized edit published a revision")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--server", type=Path, required=True)
    parser.add_argument("--openssl", type=Path, required=True)
    parser.add_argument("--scratch", type=Path, required=True)
    args = parser.parse_args()
    server = str(args.server.resolve(strict=True))
    openssl = str(args.openssl.resolve(strict=True))
    args.scratch.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=args.scratch, prefix="s38-ddl-") as directory:
        folder = Path(directory)
        for name in ("data", "log", "temp"):
            (folder / name).mkdir()
        certificates(openssl, folder)
        config = save_config(folder, timeout_ms=20000, max_connections=6)
        require(execute(server, config, "--initialize-storage").returncode == 0, "storage initialization failed")
        password = secrets.token_urlsafe(32)
        require(execute(server, config, "--bootstrap-admin", "local-admin",
                        stdin=((password + "\n") * 2).encode()).returncode == 0,
                "test administrator setup failed")
        context = ssl.create_default_context(cafile=str(folder / "ca.pem"))
        with listening(server, config) as (process, port):
            with client(port, context, password) as owner:
                exercise_ddl(owner)
                exercise_sequence_defaults(owner)
                exercise_acl(owner, port, context)
            process.kill()
            process.wait(timeout=5)
        require(execute(server, config, "--check-storage").returncode == 0, "rewritten storage verification failed")
        with listening(server, config) as (_, port):
            with client(port, context, password) as owner:
                require(select(owner, "SELECT serial FROM items WHERE id=5") == [[i64(5)]] and
                        owner.call("history_verify")["verified"] is True,
                        "restart could not recover rewritten rows and History")
    print("Table editor ALTER, rollback, row identity, History, dependency and permission checks passed")


if __name__ == "__main__":
    main()
